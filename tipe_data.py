# BAB 3: TIPE DATA DASAR PYTHON

# 1. Integer (bilangan bulat)
umur = 17
print("Umur:", umur)
print("Tipe data:", type(umur))

# 2. Float (bilangan desimal)
tinggi = 160.5
print("\nTinggi:", tinggi)
print("Tipe data:", type(tinggi))

# 3. String (teks)
nama = "Aris"
print("\nNama:", nama)
print("Tipe data:", type(nama))

# 4. Boolean (True atau False)
aktif = True
print("\nStatus aktif:", aktif)
print("Tipe data:", type(aktif))
