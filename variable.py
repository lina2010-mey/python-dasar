# BAB 4: VARIABLE PYTHON

# 1. Membuat Variable
nama = "Andi"
umur = 25
tinggi = 170.5
is_active = True

print(nama)
print(umur)
print(tinggi)
print(is_active)

# 2. Aturan Penamaan Variable
first_name = "Budi"
total_harga = 10000

print(first_name)
print(total_harga)

# 3. Multiple Assignment
a, b, c = 10, 20, 30
print(a, b, c)

x = y = z = 100
print(x, y, z)

# 4. Mengecek Tipe Data Variable
print(type(nama))
print(type(umur))
print(type(tinggi))

# 5. Menghapus Variable
nilai = 10
print(nilai)

del nilai
